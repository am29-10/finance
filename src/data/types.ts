/**
 * Ядро модели.
 *
 * Единственный источник правды — список операций. Баланс, аналитика и остаток
 * бюджета нигде не хранятся, а всегда считаются из него: иначе после правки или
 * удаления операции сохранённый баланс разойдётся с историей и починить его будет нечем.
 */

/**
 * Перевод — не доход и не расход, а перемещение денег между своими счетами.
 *
 * Без отдельного типа снятие наличных выглядело бы тратой в 30 тысяч, а
 * пополнение вклада — тратой в миллион, и структура расходов превращалась бы
 * в вымысел. В доходы и в аналитику переводы не попадают никогда, они меняют
 * только остатки двух счетов.
 */
export type OperationType = 'income' | 'expense' | 'transfer'

/** Типы, у которых есть категория и которые участвуют в аналитике. */
export type FlowType = 'income' | 'expense'

/** Дата в формате YYYY-MM-DD, всегда локальная, не UTC. */
export type DateKey = string

export interface Operation {
  id: string
  type: OperationType
  /**
   * Сумма в КОПЕЙКАХ, целым числом. Дробные рубли в JavaScript накапливают
   * ошибку округления, и на сотне операций баланс перестаёт сходиться.
   */
  amount: number
  categoryId: string
  date: DateKey
  note?: string
  createdAt: string
  /** Счёт, с которого ушли или на который пришли деньги. */
  accountId: string
  /** Счёт-получатель. Только у переводов. */
  toAccountId?: string
  /**
   * Сколько пришло на счёт-получатель, если у счетов разные валюты.
   * Курс сделки почти всегда отличается от курса в настройках, поэтому
   * обменянную сумму человек вводит сам, а не мы её вычисляем.
   */
  toAmount?: number
  /** Кредит, платёж по которому породил эту операцию. Такие операции не редактируются вручную. */
  loanId?: string
  /**
   * Ключ идемпотентности платежа по кредиту: дата планового платежа либо `p:<id досрочки>`.
   * По нему синхронизация понимает, что операция уже создана, и не задваивает расход.
   */
  loanRef?: string
}

/* ── Счета ─────────────────────────────────────────────────────────────── */

export type AccountKind = 'bank' | 'cash' | 'card' | 'deposit' | 'other'

export interface Account {
  id: string
  /** Как человек его называет: «Сбер», «Наличные», «Доллары под подушкой». */
  title: string
  kind: AccountKind
  /** Код валюты. Рублёвые счета складываются в итог как есть, остальные — по курсу. */
  currency: string
  /**
   * Остаток на счёте до первой операции в приложении, в минорных единицах.
   * Без него человеку пришлось бы заводить фиктивный доход, чтобы баланс сошёлся
   * с реальностью, и этот доход навсегда испортил бы аналитику первого месяца.
   */
  initialBalance: number
  color: string
  /** Архивный счёт не предлагается в формах, но его история остаётся. */
  archivedAt?: string
  createdAt: string
}

export interface Category {
  id: string
  title: string
  type: FlowType
  /** Ключ иконки из CategoryIcon. */
  icon: string
  color: string
  /** Встроенные категории нельзя удалить — на них ссылается история. */
  builtin?: boolean
  archivedAt?: string
}

/* ── Кредиты ───────────────────────────────────────────────────────────── */

export type LoanKind = 'mortgage' | 'consumer' | 'auto' | 'other'

/** Схема погашения. Аннуитет — равный платёж; дифференцированный — равное тело, убывающий платёж. */
export type LoanScheme = 'annuity' | 'differentiated'

/**
 * Что делает досрочное погашение с оставшимся графиком.
 * `term` — платёж прежний, кредит закрывается раньше (выгоднее по процентам).
 * `payment` — срок прежний, ежемесячный платёж падает (легче нагрузка).
 */
export type EarlyMode = 'term' | 'payment'

export interface Prepayment {
  id: string
  date: DateKey
  /** Сумма досрочного погашения в копейках. */
  amount: number
  mode: EarlyMode
  note?: string
  createdAt: string
}

export interface Loan {
  id: string
  title: string
  kind: LoanKind
  /**
   * Долг в копейках на дату `startDate`. Для нового кредита — сумма выдачи,
   * для уже действующего — остаток, который показывает банк на день заведения.
   */
  principal: number
  /**
   * Годовая ставка в СОТЫХ ДОЛЯХ ПРОЦЕНТА: 10,5 % → 1050.
   * Целое по той же причине, что и суммы: дробь в проценте уводит график на сотни рублей.
   */
  rate: number
  /** Срок в месяцах, считая от `startDate`. */
  termMonths: number
  startDate: DateKey
  /** День списания, 1–31. В коротких месяцах съезжает на последнее число. */
  paymentDay: number
  scheme: LoanScheme
  /** Режим досрочки, предлагаемый по умолчанию. */
  earlyMode: EarlyMode
  /**
   * Заводить расход на каждый плановый платёж автоматически.
   * Банк списывает сам — приложение делает то же, иначе расходы месяца занижены
   * ровно на платёж по ипотеке, а это обычно самая крупная трата.
   */
  autoExpense: boolean
  /** С какого счёта уходят платежи. Пусто — с первого активного. */
  accountId?: string
  prepayments: Prepayment[]
  /** Кредит закрыт вручную: график больше не считается, операции не создаются. */
  closedAt?: string
  createdAt: string
}

export interface Settings {
  /** Имя для приветствия на главной. */
  name: string
  /** Месячный бюджет в копейках; 0 — не задан. */
  monthlyBudget: number
  /** Хеш PIN-кода; пусто — вход без кода. Сам код нигде не хранится. */
  pinHash?: string
  /**
   * Когда в последний раз выгружали резервную копию.
   * Нужно, чтобы напомнить: в браузере данные живут ровно до чистки хранилища,
   * а на iPhone — до удаления иконки с домашнего экрана.
   */
  lastBackupAt?: string
  /** Когда напоминание о копии отложили кнопкой «Позже». */
  backupRemindedAt?: string
  /**
   * Курсы валют к рублю: сколько копеек стоит одна единица. 1 $ = 95,50 ₽ → 9550.
   * Заполняются вручную — курс из интернета стоил бы работы без сети.
   */
  rates: Record<string, number>
}

export interface FinanceData {
  version: number
  operations: Operation[]
  categories: Category[]
  accounts: Account[]
  loans: Loan[]
  settings: Settings
}

