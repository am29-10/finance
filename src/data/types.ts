/**
 * Ядро модели.
 *
 * Единственный источник правды — список операций. Баланс, аналитика и остаток
 * бюджета нигде не хранятся, а всегда считаются из него: иначе после правки или
 * удаления операции сохранённый баланс разойдётся с историей и починить его будет нечем.
 */

/**
 * Перевод — не доход и не расход, а перемещение денег между своими счетами.
 *
 * Без отдельного типа снятие наличных выглядело бы тратой в 30 тысяч, а
 * пополнение вклада — тратой в миллион, и структура расходов превращалась бы
 * в вымысел. В доходы и в аналитику переводы не попадают никогда, они меняют
 * только остатки двух счетов.
 */
export type OperationType = 'income' | 'expense' | 'transfer'

/** Типы, у которых есть категория и которые участвуют в аналитике. */
export type FlowType = 'income' | 'expense'

/** Дата в формате YYYY-MM-DD, всегда локальная, не UTC. */
export type DateKey = string

export interface Operation {
  id: string
  type: OperationType
  /**
   * Сумма в КОПЕЙКАХ, целым числом. Дробные рубли в JavaScript накапливают
   * ошибку округления, и на сотне операций баланс перестаёт сходиться.
   */
  amount: number
  categoryId: string
  date: DateKey
  note?: string
  createdAt: string
  /**
   * Счёт, с которого ушли или на который пришли деньги.
   *
   * Может отсутствовать: общие траты — «на еду за месяц ушло столько-то» —
   * человек часто не разносит по картам, и требовать счёт значило бы заставлять
   * его выдумывать. Такая операция живёт в истории и в аналитике, но ни один
   * остаток не двигает: остатки счетов ведутся отдельно и вручную.
   *
   * У перевода счёт обязателен с обоих концов — переводить не пойми откуда
   * не пойми куда бессмысленно.
   */
  accountId?: string
  /** Счёт-получатель. Только у переводов. */
  toAccountId?: string
  /**
   * Сколько пришло на счёт-получатель, если у счетов разные валюты.
   * Курс сделки почти всегда отличается от курса в настройках, поэтому
   * обменянную сумму человек вводит сам, а не мы её вычисляем.
   */
  toAmount?: number
  /** Кредит, платёж по которому породил эту операцию. Такие операции не редактируются вручную. */
  loanId?: string
  /**
   * Ключ идемпотентности платежа по кредиту: дата планового платежа либо `p:<id досрочки>`.
   * По нему синхронизация понимает, что операция уже создана, и не задваивает расход.
   */
  loanRef?: string
  /**
   * Правило повтора, создавшее операцию. В отличие от платежей по кредиту, такая
   * операция обычная: её можно править и удалять, правило её больше не тронет.
   */
  recurrenceId?: string
}

/* ── Повторяющиеся операции ────────────────────────────────────────────── */

export type RecurrencePeriod = 'week' | 'month' | 'year'

/**
 * Правило, по которому операция заводится сама.
 *
 * Подписки, аренда, зарплата приходят по календарю, а не тогда, когда о них
 * вспомнили. Пока их вносили руками, месяц с забытой подпиской выглядел
 * дешевле, чем был, — и вся статистика съезжала.
 *
 * Правило хранит не будущие операции, а способ их вычислить: даты
 * отсчитываются от `startDate` шагом в период. Уже созданное живёт своей
 * жизнью — правку суммы за конкретный месяц правило не затирает.
 */
export interface Recurrence {
  id: string
  type: OperationType
  /** Сумма в копейках — сколько списывать по умолчанию. */
  amount: number
  categoryId: string
  /** Счёт списания; как и у операции, его может не быть — см. Operation.accountId. */
  accountId?: string
  /** Счёт-получатель и полученная сумма — только у повторяющихся переводов. */
  toAccountId?: string
  toAmount?: number
  note?: string
  period: RecurrencePeriod
  /** Дата первой операции; от неё считаются все последующие. */
  startDate: DateKey
  /**
   * До какой даты операции уже заведены.
   *
   * Без этой отметки удалённая операция возвращалась бы при каждом запуске:
   * правило видело бы, что за такое-то число ничего нет, и создавало заново.
   */
  lastRunAt?: DateKey
  /** Повтор на паузе: созданное остаётся, новое не появляется. */
  pausedAt?: string
  createdAt: string
}

/* ── Счета ─────────────────────────────────────────────────────────────── */

export type AccountKind = 'bank' | 'cash' | 'card' | 'deposit' | 'other'

export interface Account {
  id: string
  /** Как человек его называет: «Сбер», «Наличные», «Доллары под подушкой». */
  title: string
  kind: AccountKind
  /** Код валюты. Рублёвые счета складываются в итог как есть, остальные — по курсу. */
  currency: string
  /**
   * Точка отсчёта остатка, в минорных единицах: сколько было на счёте до первой
   * операции в приложении.
   *
   * Она же — то, что двигается, когда человек правит остаток руками. Остаток не
   * хранится отдельно: он считается как эта точка плюс операции счёта, и «стало
   * на тысячу меньше, чем показывает банк» лечится сдвигом отсчёта, а не
   * фиктивным доходом, который навсегда испортил бы аналитику месяца.
   */
  initialBalance: number
  color: string
  /** Архивный счёт не предлагается в формах, но его история остаётся. */
  archivedAt?: string
  createdAt: string
}

export interface Category {
  id: string
  title: string
  type: FlowType
  /** Ключ иконки из CategoryIcon. */
  icon: string
  color: string
  /** Встроенные категории нельзя удалить — на них ссылается история. */
  builtin?: boolean
  archivedAt?: string
}

/* ── Кредиты ───────────────────────────────────────────────────────────── */

export type LoanKind = 'mortgage' | 'consumer' | 'auto' | 'other'

/** Схема погашения. Аннуитет — равный платёж; дифференцированный — равное тело, убывающий платёж. */
export type LoanScheme = 'annuity' | 'differentiated'

/**
 * Что делает досрочное погашение с оставшимся графиком.
 * `term` — платёж прежний, кредит закрывается раньше (выгоднее по процентам).
 * `payment` — срок прежний, ежемесячный платёж падает (легче нагрузка).
 */
export type EarlyMode = 'term' | 'payment'

export interface Prepayment {
  id: string
  date: DateKey
  /** Сумма досрочного погашения в копейках. */
  amount: number
  mode: EarlyMode
  note?: string
  createdAt: string
}

export interface Loan {
  id: string
  title: string
  kind: LoanKind
  /**
   * Долг в копейках на дату `startDate`. Для нового кредита — сумма выдачи,
   * для уже действующего — остаток, который показывает банк на день заведения.
   */
  principal: number
  /**
   * Годовая ставка в СОТЫХ ДОЛЯХ ПРОЦЕНТА: 10,5 % → 1050.
   * Целое по той же причине, что и суммы: дробь в проценте уводит график на сотни рублей.
   */
  rate: number
  /** Срок в месяцах, считая от `startDate`. */
  termMonths: number
  startDate: DateKey
  /** День списания, 1–31. В коротких месяцах съезжает на последнее число. */
  paymentDay: number
  scheme: LoanScheme
  /** Режим досрочки, предлагаемый по умолчанию. */
  earlyMode: EarlyMode
  /**
   * Заводить расход на каждый плановый платёж автоматически.
   * Банк списывает сам — приложение делает то же, иначе расходы месяца занижены
   * ровно на платёж по ипотеке, а это обычно самая крупная трата.
   */
  autoExpense: boolean
  /** С какого счёта уходят платежи. Пусто — с первого активного. */
  accountId?: string
  prepayments: Prepayment[]
  /** Кредит закрыт вручную: график больше не считается, операции не создаются. */
  closedAt?: string
  createdAt: string
}

/* ── Машина ────────────────────────────────────────────────────────────── */

/**
 * Что именно делали с машиной. Тип нужен не для отчёта, а для узнавания:
 * в списке из двадцати строк «Замена масла» и «Новая резина» ищут глазами
 * по значку, а не читают каждую подпись.
 */
export type ServiceKind = 'service' | 'tires' | 'battery' | 'repair' | 'part' | 'inspection'

/**
 * Запись в журнале обслуживания.
 *
 * Денег здесь нет намеренно: расход на сервис человек уже завёл в операциях,
 * и вторая сумма в другом месте означала бы, что одна из них рано или поздно
 * разойдётся с другой. Журнал отвечает на единственный вопрос — что и когда
 * с машиной делали.
 */
export interface ServiceRecord {
  id: string
  kind: ServiceKind
  /** Что делали: «Замена масла». */
  title: string
  date: DateKey
  /** Пробег на день работ, в километрах. Может отсутствовать: вспомнили задним числом. */
  mileage?: number
  note?: string
  /** Когда делать в следующий раз — по календарю и по пробегу; любое из двух или оба. */
  nextDate?: DateKey
  nextMileage?: number
  createdAt: string
}

export interface Vehicle {
  id: string
  /** Как человек её называет: «BMW 320i». */
  title: string
  /** Год выпуска. */
  year?: number
  plate?: string
  vin?: string
  /**
   * Текущий пробег в километрах.
   *
   * Хранится отдельно от записей журнала, потому что меняется без них: между
   * двумя визитами в сервис машина проехала десять тысяч, и напоминание
   * «следующая замена на 97 000» должно об этом знать. Запись с большим
   * пробегом двигает его сама — вводить одно и то же число дважды незачем.
   */
  mileage?: number
  records: ServiceRecord[]
  createdAt: string
}

/* ── Недвижимость ──────────────────────────────────────────────────────── */

export type PropertyKind = 'flat' | 'house' | 'room' | 'other'

/**
 * Зачем человеку этот объект. От назначения зависит, что о нём вообще имеет
 * смысл спрашивать: у сдаваемой квартиры важны арендатор и срок договора,
 * у своей — этаж и год ремонта, и валить это в одну карточку значило бы
 * показывать каждому половину полей впустую.
 */
export type PropertyPurpose = 'living' | 'rent' | 'invest' | 'other'

export interface Property {
  id: string
  /** «Квартира на Ленина» — так человек её и называет в разговоре. */
  title: string
  kind: PropertyKind
  purpose: PropertyPurpose
  address?: string
  /**
   * Площадь в ДЕСЯТЫХ ДОЛЯХ квадратного метра: 62,5 м² → 625.
   * Целое по той же причине, что и суммы: дробь в числе накапливает ошибку,
   * а половина метра в документах на квартиру встречается постоянно.
   */
  area?: number
  rooms?: number
  floor?: number
  note?: string
  /** Арендатор и срок договора — только у сдаваемой. */
  tenant?: string
  contractUntil?: DateKey
  /** День месяца, когда приходит оплата аренды, 1–31. */
  rentDay?: number
  /** Год последнего ремонта — у той, в которой живут. */
  renovationYear?: number
  createdAt: string
}

export interface Settings {
  /** Месячный бюджет в копейках; 0 — не задан. */
  monthlyBudget: number
  /** Хеш PIN-кода; пусто — вход без кода. Сам код нигде не хранится. */
  pinHash?: string
  /**
   * Когда в последний раз выгружали резервную копию.
   * Нужно, чтобы напомнить: в браузере данные живут ровно до чистки хранилища,
   * а на iPhone — до удаления иконки с домашнего экрана.
   */
  lastBackupAt?: string
  /** Когда напоминание о копии отложили кнопкой «Позже». */
  backupRemindedAt?: string
  /**
   * Курсы валют к рублю: сколько копеек стоит одна единица. 1 $ = 95,50 ₽ → 9550.
   * Заполняются вручную — курс из интернета стоил бы работы без сети.
   */
  rates: Record<string, number>
}

export interface FinanceData {
  version: number
  operations: Operation[]
  categories: Category[]
  accounts: Account[]
  loans: Loan[]
  recurrences: Recurrence[]
  /**
   * Машины и недвижимость. С деньгами не связаны ничем: ни в баланс, ни в
   * аналитику не попадают. Это справочник о вещах, а не ещё один вид счёта, —
   * стоимость квартиры, записанная в приложении, устарела бы в тот же месяц.
   */
  vehicles: Vehicle[]
  properties: Property[]
  settings: Settings
}

