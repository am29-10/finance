/**
 * Цветные доходные категории проверены на все пары сразу — в кольце любые две
 * могут оказаться рядом. Аренда добавлялась шестой, и её цвет выбирался так,
 * чтобы худшая пара в наборе от него не ухудшилась ни при обычном зрении, ни
 * при дейтеранопии, ни при протанопии: тёмная малина ни с одной из прежних
 * пяти не сходится ближе, чем они сходятся между собой.
 */
const INCOMES: Array<[string, string, string, string]> = [
  ['salary', 'Зарплата', 'wallet', '#008300'],
  ['rent-income', 'Аренда квартиры', 'key', '#9d174d'],
  ['freelance', 'Фриланс', 'laptop', '#2a78d6'],
  ['business', 'Бизнес', 'briefcase', '#4a3aa7'],
  ['investments', 'Инвестиции', 'chart', '#eda100'],
  ['gift', 'Подарок', 'gift', '#e87ba4'],
  [OTHER_INCOME_ID, 'Другое', 'dots', REST_COLOR],
]

export function defaultCategories(): Category[] {
  return [
    ...EXPENSES.map(([id, title, icon, color]) => ({
      id,
      title,
      icon,
      color,
      type: 'expense' as const,
      builtin: true,
    })),
    ...INCOMES.map(([id, title, icon, color]) => ({
      id,
      title,
      icon,
      color,
      type: 'income' as const,
      builtin: true,
    })),
  ]
}

/**
 * Категории, слитые с другими: откуда → куда.
 *
 * Разделять кафе и рестораны оказалось работой без ответа: граница между
 * «посидели в кафе» и «сходили в ресторан» проходит по настроению, а не по
 * счёту, и одна и та же трата попадала то туда, то сюда — статистика по обеим
 * категориям выходила недостоверной.
 *
 * Интернет и телефон ушли к коммунальным по другой причине: это платежи одного
 * рода — обязательные, ежемесячные, за квартиру и связь, — и часто вообще один
 * счёт от одного провайдера. По отдельности каждая из трёх категорий занимала
 * в структуре расходов пару процентов и терялась в хвосте, а вместе они
 * отвечают на вопрос «сколько стоит просто жить в квартире».
 *
 * Просто убрать категорию из кода нельзя: на неё ссылается уже заведённая
 * история, и операции остались бы «без категории». Поэтому слияния перечислены
 * здесь, а миграция переносит по ним ссылки и убирает опустевшую категорию.
 */
export const MERGED_CATEGORIES: Record<string, string> = {
  restaurants: 'cafe',
  internet: 'utilities',
  phone: 'utilities',
}

/** Куда попадают операции, чья категория была удалена. */
export const FALLBACK_CATEGORY: Record<'income' | 'expense', string> = {
  expense: OTHER_EXPENSE_ID,
  income: OTHER_INCOME_ID,
}
